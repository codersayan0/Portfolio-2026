"""Fit a TF-IDF nearest-neighbor intent model on the public portfolio dataset."""
import json, math, re
from collections import Counter
from pathlib import Path
ROOT=Path(__file__).resolve().parent

STOP=set('a an the is are was were what who how do does did can could would should of to in on at for from about his he him your you me my i tell please this that and it they their which where when has have had sayan mandal know'.split())
def tokens(s):
    return [w for w in re.findall(r'[a-z0-9]+',s.lower().replace('c++','cplusplus').replace('c#','csharp')) if w not in STOP]

def train():
    data=json.loads((ROOT/'knowledge.json').read_text())
    rows=[(i,q) for i,item in enumerate(data) for q in item['examples']]
    docs=[tokens(q) for _,q in rows]
    df=Counter(w for doc in docs for w in set(doc))
    idf={w:math.log((len(docs)+1)/(n+1))+1 for w,n in df.items()}
    vectors=[]
    for (i,q),doc in zip(rows,docs):
        v={w:n*idf[w] for w,n in Counter(doc).items()}; norm=math.sqrt(sum(x*x for x in v.values())) or 1
        vectors.append({'intent':i,'v':{w:round(x/norm,6) for w,x in v.items()}})
    model={'idf':idf,'vectors':vectors,'knowledge':data}
    (ROOT/'model.json').write_text(json.dumps(model,ensure_ascii=False,separators=(',',':')))
    (ROOT/'model-data.js').write_text('/* Generated by train.py; public portfolio data. */\nwindow.PORTFOLIO_CHAT_MODEL = '+json.dumps(model,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
    print(f'Trained {len(rows)} examples across {len(data)} intents; {len(idf)} terms.')
if __name__=='__main__':train()
